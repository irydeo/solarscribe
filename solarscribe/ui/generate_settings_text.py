# Generates ui/settings_text.py from config.schema.SCHEMA.
#
# Why a generated table: every schema key carries a "why" that the settings
# dialog shows as its tooltip. lupdate can only mark a string it sees in the
# source, so the table wraps each why in QT_TRANSLATE_NOOP("Settings", ...).
# Hand-maintaining 111 copies would drift the first time a key changes; this
# module is the single source and a test fails when the committed file no
# longer matches SCHEMA.
#
# The generator itself does not import Qt: it writes the QT_TRANSLATE_NOOP call
# as text. The generated module imports the macro and is safe to import in the
# UI.
#
# Run it with:
#   python -m solarscribe.ui.generate_settings_text

from __future__ import annotations

import json
from pathlib import Path

from solarscribe.config.schema import SCHEMA

__all__ = ["MODULE_PATH", "render_module", "write_module"]

MODULE_PATH = Path(__file__).with_name("settings_text.py")

HEADER = """############################################################
# -*- coding: utf-8 -*-
#
# SolarScribe - ui settings text module
# Python  v3.12
#
# Francisco José Calvo Fernández
# (c) 2026
#
# Licence GPL v3
#
############################################################
"""


# @args: text - the source why text
# @return: a JSON string literal, double quoted and UTF-8 safe
def _literal(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


# @args: none
# @return: the complete settings_text.py content, deterministic for a SCHEMA
def render_module() -> str:
    lines = [
        HEADER,
        "",
        "# Generated by solarscribe.ui.generate_settings_text from config.schema.",
        "# Do not edit by hand: edit the schema why text and regenerate. The test",
        "# test_ui_settings_text.py fails when this file drifts from SCHEMA.",
        "#",
        "# QT_TRANSLATE_NOOP marks each runtime tooltip for lupdate without",
        "# translating it at import time. The dialog calls QCoreApplication.translate",
        "# with the same \"Settings\" context.",
        "",
        "from __future__ import annotations",
        "",
        "from PySide6.QtCore import QT_TRANSLATE_NOOP",
        "",
        '__all__ = ["SETTINGS_WHY"]',
        "",
        "# @args: none. It is a module table",
        "# @return: the source why text per (section, name), marked for translation",
        "SETTINGS_WHY: dict[tuple[str, str], str] = {",
    ]
    for key in SCHEMA:
        lines.append(
            f'    ({key.section!r}, {key.name!r}): '
            f'QT_TRANSLATE_NOOP("Settings", {_literal(key.why)}),'
        )
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


# @args: none
# @return: the path written, settings_text.py next to this module
def write_module() -> Path:
    MODULE_PATH.write_text(render_module(), encoding="utf-8")
    return MODULE_PATH


# @args: none
def _main() -> None:
    path = write_module()
    print(f"wrote {path} ({len(SCHEMA)} marked strings)")


if __name__ == "__main__":
    _main()
